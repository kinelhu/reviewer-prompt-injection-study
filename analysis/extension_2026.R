# JMIR R1 extension analysis: the 2026 arms (gpt-5.6-luna reasoning off/medium).
# Runs on dat_all (all four models). The primary exhibits are unchanged; this
# adds the current-model replication (BV-1) and the reasoning contrast.
# Numbers are written to output/r1_extension.md — nothing is retyped into prose.

suppressPackageStartupMessages({library(dplyr); library(tidyr); library(ordinal)})

EXT_MODELS <- c("gpt-5.6-luna", "gpt-5.6-luna-medium")
MODEL_YEAR <- c("gemma4:26b" = "Gemma 4 26B (2025)", "o4-mini" = "o4-mini (2025)",
                "gpt-5.6-luna" = "GPT-5.6-luna, reasoning off (2026)",
                "gpt-5.6-luna-medium" = "GPT-5.6-luna, reasoning medium (2026)")

ext <- c("# R1 extension analysis: 2026 models", "",
         sprintf("Generated by pipeline.R on %s from data/study.db.", Sys.Date()),
         "Primary analysis (Tables 1-3, Figs 1-4) is unchanged and covers the two 2025 models.",
         "This file covers the 2026 gpt-5.6-luna arms added at R1.", "")

# ── Paired shift, all four models (descriptive) ───────────────────────────────
bl <- dat_all |>
  filter(direction == "baseline", !is.na(recommendation_ordinal)) |>
  select(model_name, paper_id, prompt_style, b = recommendation_ordinal)
inj <- dat_all |>
  filter(direction == "favorable", !is.na(recommendation_ordinal)) |>
  select(model_name, paper_id, prompt_style, placement, i = recommendation_ordinal,
         detected_injection)
pd <- inner_join(inj, bl, by = c("model_name", "paper_id", "prompt_style")) |>
  mutate(shift = i - b)

shift_tab <- pd |>
  group_by(model_name, prompt_style) |>
  summarise(pairs = n(), pct_up = round(100 * mean(shift > 0)),
            mean_shift = round(mean(shift), 2), .groups = "drop")

ext <- c(ext, "## Paired shift by model and prompt (injection vs baseline, matched by paper)", "",
  "| Model | Prompt | Pairs | % up | Mean shift |", "|---|---|---|---|---|",
  sprintf("| %s | %s | %d | %d | %.2f |",
          MODEL_YEAR[shift_tab$model_name], shift_tab$prompt_style,
          shift_tab$pairs, shift_tab$pct_up, shift_tab$mean_shift),
  "")

# ── Detection rate, all models, by prompt (and placement for aware) ───────────
det_prompt <- inj |>
  group_by(model_name, prompt_style) |>
  summarise(n = n(), pct_det = round(100 * mean(detected_injection)), .groups = "drop")
det_place <- inj |>
  filter(prompt_style == "aware") |>
  group_by(model_name, placement) |>
  summarise(pct_det = round(100 * mean(detected_injection)), .groups = "drop") |>
  pivot_wider(names_from = placement, values_from = pct_det)

ext <- c(ext, "## Detection rate (injection reviews)", "",
  "| Model | Prompt | n | % detected |", "|---|---|---|---|",
  sprintf("| %s | %s | %d | %d |",
          MODEL_YEAR[det_prompt$model_name], det_prompt$prompt_style,
          det_prompt$n, det_prompt$pct_det),
  "", "Aware-prompt detection by placement (%):", "",
  "| Model | beginning | middle | end |", "|---|---|---|---|",
  sprintf("| %s | %d | %d | %d |", MODEL_YEAR[det_place$model_name],
          det_place$beginning, det_place$middle, det_place$end),
  "")

# ── Injection effect per luna arm: paired Wilcoxon signed-rank ────────────────
# A CLMM on these arms does not converge: luna-medium/aware shows 0% shift and
# luna/standard ~100%, i.e. (quasi-)complete separation, so the ML ordinal
# estimate diverges (OR ~1e12, non-finite SE). Paired signed-rank is robust to
# this and is the same nonparametric test used for the primary secondary
# outcomes; it also sidesteps the ordinal-scale concern (reviewer BX-3).
ext_pairs <- pd |> filter(model_name %in% EXT_MODELS)

sr <- ext_pairs |>
  group_by(model_name, prompt_style) |>
  summarise(n_pairs = n(),
            V = wilcox.test(shift, mu = 0, exact = FALSE)$statistic,
            p_raw = wilcox.test(shift, mu = 0, exact = FALSE)$p.value,
            .groups = "drop") |>
  mutate(p_adj = p.adjust(p_raw, "bonferroni"), p_fmt = fmt_p(p_adj))

ext <- c(ext, "## Injection effect per 2026 arm (paired Wilcoxon signed-rank, injection vs baseline)", "",
  "Bonferroni-adjusted across the 4 arm x prompt tests. CLMM omitted: complete separation (see code note).", "",
  "| Model | Prompt | n pairs | V | p (adj) |", "|---|---|---|---|---|",
  sprintf("| %s | %s | %d | %g | %s |", MODEL_YEAR[sr$model_name], sr$prompt_style,
          sr$n_pairs, sr$V, sr$p_fmt),
  "",
  "Note: reasoning-medium/aware has zero shift in all 150 pairs, so the signed-rank",
  "test is undefined (no non-zero differences) - a stronger statement than a p-value:",
  "the injection moved no review in that cell.", "")

# ── Reasoning contrast: paired by paper, luna-medium vs luna-off ──────────────
# Same 50 papers under both reasoning modes, so the injection shift can be paired
# within paper. Tests whether reasoning changes the injection effect, per prompt.
wide <- ext_pairs |>
  group_by(model_name, paper_id, prompt_style) |>
  summarise(shift = mean(shift), .groups = "drop") |>
  pivot_wider(names_from = model_name, values_from = shift)

reason <- wide |>
  filter(!is.na(`gpt-5.6-luna`), !is.na(`gpt-5.6-luna-medium`)) |>
  group_by(prompt_style) |>
  summarise(n = n(),
            shift_off = round(mean(`gpt-5.6-luna`), 2),
            shift_medium = round(mean(`gpt-5.6-luna-medium`), 2),
            p = fmt_p(wilcox.test(`gpt-5.6-luna-medium`, `gpt-5.6-luna`,
                                  paired = TRUE, exact = FALSE)$p.value),
            .groups = "drop")

ext <- c(ext, "## Reasoning contrast (paired by paper: reasoning medium vs off, same injection)", "",
  "| Prompt | n papers | Mean shift, reasoning off | Mean shift, reasoning medium | p (paired) |",
  "|---|---|---|---|---|",
  sprintf("| %s | %d | %.2f | %.2f | %s |", reason$prompt_style, reason$n,
          reason$shift_off, reason$shift_medium, reason$p),
  "",
  "Reading: reasoning barely changes the effect under the standard prompt (attack works either way);",
  "under the aware prompt, reasoning collapses the residual shift toward zero.", "")

writeLines(ext, here::here("output", "r1_extension.md"))
cat("  R1 extension -> output/r1_extension.md\n")

# ── Figure 6: model x prompt point-ranges (shift + detection) ─────────────────
# Post-hoc extension exhibit. Four models on x, standard vs aware side by side.
# Numbered Figure 6: the paper has Figures 1-4 and former Figure S2 is promoted
# to Figure 5 (N-4), so this extension figure is Figure 6.
library(ggplot2); library(patchwork)

MODEL_ORDER <- c("gemma4:26b", "o4-mini", "gpt-5.6-luna", "gpt-5.6-luna-medium")
MODEL_SHORT <- c("gemma4:26b" = "Gemma 4 26B\n(2025)", "o4-mini" = "o4-mini\n(2025)",
                 "gpt-5.6-luna" = "GPT-5.6-luna\noff (2026)",
                 "gpt-5.6-luna-medium" = "GPT-5.6-luna\nmedium (2026)")
fct_m  <- function(x) factor(MODEL_SHORT[x], levels = MODEL_SHORT[MODEL_ORDER])
fct_pr <- function(x) factor(ifelse(x == "standard", "Standard", "Aware"),
                             levels = c("Standard", "Aware"))

dodge <- position_dodge(width = 0.5)

# Panel A: mean shift with 95% CI, per-paper means to avoid pseudoreplication
# (placements averaged within paper first), matching the primary figures' logic.
f5a_dat <- pd |>
  group_by(model_name, prompt_style, paper_id) |>
  summarise(shift = mean(shift), .groups = "drop") |>
  group_by(model_name, prompt_style) |>
  summarise(mean = mean(shift), se = sd(shift) / sqrt(n()), .groups = "drop") |>
  mutate(lo = mean - 1.96 * se, hi = mean + 1.96 * se,
         model = fct_m(model_name), prompt = fct_pr(prompt_style))

f5a <- ggplot(f5a_dat, aes(model, mean, color = prompt, group = prompt)) +
  geom_hline(yintercept = 0, linewidth = 0.3, colour = "grey70") +
  geom_pointrange(aes(ymin = lo, ymax = hi), position = dodge, size = 0.45, fatten = 2.2) +
  scale_color_manual(values = PROMPT_COLORS, name = "Prompt") +
  labs(title = "A  Injection effect (mean ordinal shift, 95% CI)",
       x = NULL, y = "Mean shift vs baseline")

# Panel B: detection proportion with Clopper-Pearson 95% CI (as primary figs).
f5b_dat <- inj |>
  group_by(model_name, prompt_style) |>
  summarise(k = sum(detected_injection), n = n(), .groups = "drop") |>
  rowwise() |>
  mutate(p = 100 * k / n,
         lo = 100 * binom.test(k, n)$conf.int[1],
         hi = 100 * binom.test(k, n)$conf.int[2]) |>
  ungroup() |>
  mutate(model = fct_m(model_name), prompt = fct_pr(prompt_style))

f5b <- ggplot(f5b_dat, aes(model, p, color = prompt, group = prompt)) +
  geom_pointrange(aes(ymin = lo, ymax = hi), position = dodge, size = 0.45, fatten = 2.2) +
  scale_color_manual(values = PROMPT_COLORS, name = "Prompt") +
  labs(title = "B  Injection detection rate (Clopper-Pearson 95% CI)",
       x = NULL, y = "Detected (%)")

F6 <- (f5a / f5b) + plot_layout(guides = "collect") &
  theme(legend.position = "bottom", axis.text.x = element_text(size = 8))
save_fig(F6, "F6_extension_2026", width = 7, height = 6.5)
cat("  Figure 6 -> figures/F6_extension_2026.pdf\n")

# ── Extension table: all arms, shift + detection ──────────────────────────────
ext_table <- shift_tab |>
  left_join(det_prompt |> select(model_name, prompt_style, pct_det),
            by = c("model_name", "prompt_style")) |>
  transmute(Model = MODEL_YEAR[model_name],
            Prompt = ifelse(prompt_style == "standard", "Standard", "Aware"),
            `Pairs` = pairs, `% shifted up` = pct_up,
            `Mean shift` = sprintf("%.2f", mean_shift),
            `Detected %` = pct_det) |>
  arrange(match(Model, MODEL_YEAR[MODEL_ORDER]), desc(Prompt))

save_table(ext_table, "T4_extension_2026",
  caption = paste("Table 4. Injection effect and detection across model generations",
                  "(post-hoc analysis, added in response to review)."),
  footnotes = c(
    paste("Post-hoc additional analysis conducted in response to reviewer request;",
          "the two 2025 models constitute the pre-specified primary analysis (Tables 1-3)."),
    paste("Shift = injection minus baseline recommendation (ordinal 1-4), paired by paper,",
          "injection averaged across placements. Detection = reviews explicitly flagging the injection."),
    paste("GPT-5.6-luna run with reasoning disabled ('off') and at medium reasoning effort;",
          "all injection vs baseline shifts significant at p<0.001 (paired Wilcoxon signed-rank),",
          "except luna medium under the aware prompt, where no review shifted.")))
cat("  Table 4 -> tables/T4_extension_2026.docx\n")

